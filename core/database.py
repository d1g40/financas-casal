"""Acesso ao banco de dados: SQLite (uso local) ou PostgreSQL (nuvem).

O resto do código só usa `transacao()` / `conectar()` e `conn.execute("... ?", params)`.
Quem decide o banco é a variável de ambiente DATABASE_URL:

  * sem DATABASE_URL  -> SQLite em data/financas.db (ou FINANCAS_DB), como antes;
  * com DATABASE_URL  -> PostgreSQL (ex.: Neon), usado quando o app está publicado.

Para o SQL escrito em estilo SQLite continuar valendo no PostgreSQL, a classe
`ConexaoPG` converte os parâmetros ('?' -> '%s') e devolve `lastrowid`
(via RETURNING id), de modo que `conn.execute(...).lastrowid` funciona nos dois.
"""
from __future__ import annotations

import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator, Optional, Sequence, Union

RAIZ = Path(__file__).resolve().parent.parent
CAMINHO_SCHEMA = RAIZ / "db" / "schema.sql"
# Pode ser sobrescrito com a variável de ambiente FINANCAS_DB (útil em testes).
CAMINHO_BANCO = Path(os.environ.get("FINANCAS_DB", RAIZ / "data" / "financas.db"))
PESSOAS_PADRAO = ("David", "Mylena")
NOMES_ANTIGOS = {"Milena": "Mylena"}  # grafia corrigida: bancos criados antes são ajustados sozinhos

# Tabelas cuja chave primária NÃO é a coluna 'id' (não recebem RETURNING id no PostgreSQL).
TABELAS_SEM_ID = frozenset({"compra_pagamento", "compra_rateio"})

# Tipos de cada banco para os marcadores do schema.sql.
TIPOS = {
    "sqlite": {"PK": "INTEGER PRIMARY KEY", "REAL": "REAL", "HOJE": "(date('now'))"},
    "postgres": {"PK": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                 "REAL": "DOUBLE PRECISION",
                 "HOJE": "(to_char(CURRENT_DATE, 'YYYY-MM-DD'))"},
}


# ----------------------------------------------------------------------
# Escolha do banco
# ----------------------------------------------------------------------
def url_postgres() -> Optional[str]:
    """Endereço do PostgreSQL (DATABASE_URL), ou None para usar o SQLite local."""
    return os.environ.get("DATABASE_URL", "").strip() or None


def modo_banco() -> str:
    return "postgres" if url_postgres() else "sqlite"


# ----------------------------------------------------------------------
# Tradução SQLite -> PostgreSQL
# ----------------------------------------------------------------------
class Linha(dict):
    """Linha de resultado: acessível por nome (r['nome']) e por posição (r[0]), como o sqlite3.Row."""
    __slots__ = ()

    def __getitem__(self, chave):
        if isinstance(chave, int):
            return list(self.values())[chave]
        return super().__getitem__(chave)


def _fabrica_linhas(cursor):
    """row_factory do psycopg: monta `Linha` com os nomes das colunas."""
    nomes = [coluna.name for coluna in cursor.description] if cursor.description else []
    return lambda valores: Linha(zip(nomes, valores))


def traduzir_sql(sql: str, com_parametros: bool) -> str:
    """Troca os marcadores '?' (SQLite) por '%s' (psycopg); '%' literal vira '%%'."""
    if not com_parametros:
        return sql
    return sql.replace("%", "%%").replace("?", "%s")


_INSERT = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.IGNORECASE)


def _precisa_returning(sql: str) -> bool:
    achou = _INSERT.match(sql)
    return bool(achou) and achou.group(1).lower() not in TABELAS_SEM_ID and "returning" not in sql.lower()


class CursorPG:
    """Cursor com a mesma interface mínima do sqlite3 (fetchone/fetchall/iteração/lastrowid/rowcount)."""

    def __init__(self, cursor: Any, lastrowid: Optional[int] = None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)


class ConexaoPG:
    """Envolve uma conexão do psycopg para aceitar SQL em estilo SQLite."""
    dialeto = "postgres"

    def __init__(self, bruta: Any):
        self._bruta = bruta

    def execute(self, sql: str, params: Optional[Sequence[Any]] = None) -> CursorPG:
        cursor = self._bruta.cursor()
        retorna_id = _precisa_returning(sql)
        if retorna_id:
            sql = sql.rstrip().rstrip(";") + " RETURNING id"
        valores = tuple(params) if params is not None else None
        cursor.execute(traduzir_sql(sql, valores is not None), valores)
        lastrowid = None
        if retorna_id:
            linha = cursor.fetchone()  # None quando ON CONFLICT DO NOTHING não inseriu nada
            lastrowid = linha["id"] if linha else None
        return CursorPG(cursor, lastrowid)

    def executemany(self, sql: str, lista: Sequence[Sequence[Any]]) -> CursorPG:
        cursor = self._bruta.cursor()
        cursor.executemany(traduzir_sql(sql, True), [tuple(item) for item in lista])
        return CursorPG(cursor)

    def commit(self) -> None:
        self._bruta.commit()

    def rollback(self) -> None:
        self._bruta.rollback()

    def close(self) -> None:
        self._bruta.close()


# ----------------------------------------------------------------------
# Conexões
# ----------------------------------------------------------------------
def conectar(caminho: Optional[Union[str, Path]] = None) -> sqlite3.Connection:
    """Abre uma conexão SQLite com linhas acessíveis por nome e chaves estrangeiras ativas."""
    destino = Path(caminho) if caminho else CAMINHO_BANCO
    destino.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(destino)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")  # o SQLite não ativa isso por padrão
    return conn


_pool: Any = None
_trava_pool = threading.Lock()


def _obter_pool() -> Any:
    """Pool de conexões com o PostgreSQL (criado na primeira vez). None se psycopg_pool não estiver instalado."""
    global _pool
    with _trava_pool:
        if _pool is None:
            try:
                from psycopg_pool import ConnectionPool
            except ImportError:
                return None
            _pool = ConnectionPool(
                conninfo=url_postgres(), min_size=1, max_size=4, open=False,
                # prepare_threshold=None: compatível com os endereços "pooled" (pgbouncer) do Neon.
                kwargs={"row_factory": _fabrica_linhas, "prepare_threshold": None},
                # Testa a conexão antes de usar: o Neon encerra conexões ociosas.
                check=ConnectionPool.check_connection)
            _pool.open()
        return _pool


@contextmanager
def _transacao_postgres() -> Iterator[ConexaoPG]:
    pool = _obter_pool()
    if pool is not None:
        with pool.connection() as bruta:  # commit ao sair sem erro, rollback em caso de exceção
            yield ConexaoPG(bruta)
        return
    import psycopg  # sem pool: uma conexão nova por transação (mais lento, mas funciona)
    bruta = psycopg.connect(url_postgres(), row_factory=_fabrica_linhas, prepare_threshold=None)
    try:
        yield ConexaoPG(bruta)
        bruta.commit()
    except Exception:
        bruta.rollback()
        raise
    finally:
        bruta.close()


@contextmanager
def transacao(caminho: Optional[Union[str, Path]] = None) -> Iterator[Any]:
    """Abre uma transação: commit ao sair sem erro, rollback em caso de exceção.

    Sem `caminho` e com DATABASE_URL definida, usa o PostgreSQL; caso contrário, o SQLite.
    """
    if caminho is None and url_postgres():
        with _transacao_postgres() as conn:
            yield conn
        return
    conn = conectar(caminho)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


# ----------------------------------------------------------------------
# Esquema
# ----------------------------------------------------------------------
def montar_schema(dialeto: str) -> str:
    """Lê db/schema.sql e troca os marcadores {PK}, {REAL} e {HOJE} pelos tipos do banco escolhido."""
    texto = CAMINHO_SCHEMA.read_text(encoding="utf-8")
    for marcador, tipo in TIPOS[dialeto].items():
        texto = texto.replace("{" + marcador + "}", tipo)
    return texto


def comandos_sql(texto: str) -> list[str]:
    """Separa um script SQL em comandos (ignora comentários '--')."""
    sem_comentarios = re.sub(r"--[^\n]*", "", texto)
    return [c.strip() for c in sem_comentarios.split(";") if c.strip()]


def inicializar_banco(conn: Any) -> None:
    """Cria as tabelas (se não existirem), ajusta nomes antigos e cadastra as pessoas padrão."""
    if isinstance(conn, ConexaoPG):
        conn.execute("SELECT pg_advisory_xact_lock(7311)")  # evita corrida se duas sessões iniciarem juntas
        for comando in comandos_sql(montar_schema("postgres")):
            conn.execute(comando)
    else:
        conn.executescript(montar_schema("sqlite"))
    for antigo, novo in NOMES_ANTIGOS.items():
        conn.execute("UPDATE pessoa SET nome = ? WHERE nome = ? "
                     "AND NOT EXISTS (SELECT 1 FROM pessoa WHERE nome = ?)", (novo, antigo, novo))
    for nome in PESSOAS_PADRAO:
        conn.execute("INSERT INTO pessoa (nome) VALUES (?) ON CONFLICT (nome) DO NOTHING", (nome,))


def garantir_banco(caminho: Optional[Union[str, Path]] = None) -> None:
    """Atalho para inicializar o banco padrão (ou o do caminho informado)."""
    with transacao(caminho) as conn:
        inicializar_banco(conn)
