def test_migracao_milena_para_mylena():
    with tempfile.TemporaryDirectory() as pasta:
        c = conectar(Path(pasta) / "antigo.db")
        c.executescript(montar_schema("sqlite"))
        c.execute("INSERT INTO pessoa (nome) VALUES ('David')")
        c.execute("INSERT INTO pessoa (nome) VALUES ('Milena')")
        id_antigo = c.execute("SELECT id FROM pessoa WHERE nome = 'Milena'").fetchone()["id"]
        inicializar_banco(c)
        inicializar_banco(c)  # rodar de novo não duplica nada
        nomes = {r["id"]: r["nome"] for r in c.execute("SELECT id, nome FROM pessoa")}
        assert sorted(nomes.values()) == ["David", "Mylena"] and nomes[id_antigo] == "Mylena"
        c.close()


