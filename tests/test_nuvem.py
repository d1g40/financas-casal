EMAILS = mapa_emails({"David": " David@Gmail.com ", "Mylena": "mylena@gmail.com"})


def _decidir(**kw):
    base = dict(na_nuvem=True, auth_configurado=True, emails=EMAILS, logado=True,
                email="david@gmail.com", email_verificado=True)
    return decidir_acesso(**{**base, **kw})


def test_decidir_acesso():
    assert EMAILS == {"david@gmail.com": "David", "mylena@gmail.com": "Mylena"}
    assert _decidir().estado == "liberado" and _decidir().pessoa == "David"
    assert _decidir(email="MYLENA@gmail.com").pessoa == "Mylena"
    assert _decidir(logado=False).estado == "pedir_login"
    assert _decidir(email="intruso@gmail.com").estado == "negado"
    assert _decidir(email=None).estado == "negado"
    assert _decidir(email_verificado=False).estado == "negado"
    # na nuvem, sem login configurado (ou sem lista de e-mails), o app NUNCA abre
    assert _decidir(auth_configurado=False).estado == "nao_configurado"
    assert _decidir(emails={}).estado == "nao_configurado"
    # uso local sem login configurado abre direto; local com login configurado exige login
    assert _decidir(na_nuvem=False, auth_configurado=False, logado=False).estado == "sem_login"
    assert _decidir(na_nuvem=False, logado=False).estado == "pedir_login"


def test_backup_zip(conn):
    pessoas = {p["nome"]: p["id"] for p in fc.listar_pessoas(conn)}
    fc.adicionar_receita(conn, pessoas["David"], "Salário", 5000, "2026-11")
    with zipfile.ZipFile(io.BytesIO(gerar_backup_zip(conn))) as z:
        nomes = z.namelist()
        assert len(nomes) == len(TABELAS) + 1 and "LEIA-ME.txt" in nomes
        pessoa_csv = z.read("01_pessoa.csv").decode("utf-8")
        receita_csv = z.read("02_receita.csv").decode("utf-8")
    assert pessoa_csv.startswith("﻿") and "Mylena" in pessoa_csv and "David" in pessoa_csv
    assert "Salário" in receita_csv and "5000" in receita_csv


