class CursorFalso:
    def __init__(self, registro, linha):
        self.registro, self.linha, self.rowcount = registro, linha, 1

    def execute(self, sql, params=None):
        self.registro.append((sql, params))

    def executemany(self, sql, lista):
        self.registro.append((sql, list(lista)))

    def fetchone(self):
        return self.linha

    def fetchall(self):
        return []

    def __iter__(self):
        return iter([])


class ConexaoFalsa:
    def __init__(self, linha=None):
        self.registro, self.linha = [], linha

    def cursor(self):
        return CursorFalso(self.registro, self.linha)


def test_traduzir_sql():
    assert traduzir_sql("SELECT * FROM t WHERE a = ? AND b LIKE '%x%'", True) == \
        "SELECT * FROM t WHERE a = %s AND b LIKE '%%x%%'"
    assert traduzir_sql("SELECT '%x%'", False) == "SELECT '%x%'"  # sem parâmetros, nada muda


