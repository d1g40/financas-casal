def test_esquema_postgres_e_consistente():
    pg = montar_schema("postgres")
    sem_comentarios = re.sub(r"--[^\n]*", "", pg)
    assert "{" not in pg and "}" not in pg
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sem_comentarios
    assert "DOUBLE PRECISION" in sem_comentarios and not re.search(r"\bREAL\b", sem_comentarios)
    assert "date('now')" not in sem_comentarios and "to_char(CURRENT_DATE" in sem_comentarios

    comandos = comandos_sql(pg)
    assert all(c.startswith(("CREATE TABLE IF NOT EXISTS", "CREATE INDEX IF NOT EXISTS")) for c in comandos)
    tabelas_schema = set(re.findall(r"CREATE TABLE IF NOT EXISTS (\w+)", sem_comentarios))
    assert tabelas_schema == set(TABELAS)  # o backup cobre todas as tabelas, nenhuma sobrando

    sqlite = montar_schema("sqlite")
    assert "INTEGER PRIMARY KEY" in sqlite and "date('now')" in sqlite and "{" not in sqlite


